@lru_cache(maxsize=1)
def _environment() -> Environment:
    embedded = {
        f"{name.value}.jinja2": source for name, source in _TEMPLATES.items()
    }
    return Environment(
        loader=ChoiceLoader(
            [
                FileSystemLoader(Path(__file__).with_name("templates")),
                DictLoader(embedded),
            ]
        ),
        autoescape=False,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
        undefined=StrictUndefined,
    )


GENERATED_HEADER = render_template(TemplateName.GENERATED_HEADER)
